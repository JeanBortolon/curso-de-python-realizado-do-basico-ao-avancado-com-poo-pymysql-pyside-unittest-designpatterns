# Declaração de variáveis
adicao = 10 + 10
subtracao = 10 - 10
multiplicacao = 10 * 10
divisao = 10 / 2.2  # retorna float
divisao_inteira = 10 // 2.2  # trunca sem dec
exponenciacao = 2 ** 3
modulo = 55 % 2  # resto da divisão

print("Valor da adição:", adicao)
print("Valor da subtração:", subtracao)
print("Valor da multiplicação:", multiplicacao)
print("Valor da divisão:", divisao)
print("Valor da divisão inteira:", divisao_inteira)
print("Valor da exponenciação:", exponenciacao)
print("Valor do módulo:", modulo)
print(" 10 é multiplo de 8?", 10 % 8 == 0)
print(" 16 é multiplo de 8?", 16 % 8 == 0)
print("O Número é par ?", 10 % 2 == 0)
print("O Número é par ?", 15 % 2 == 0)

