# Concatenando Strings utilizando sinal de +
concatenacao = 'A' + 'B' + 'C'
print(concatenacao)

# Conversão ou Coerção de Int para Str
# Concatenando o valor numérico com espaço e anos
descricao_idade = str(30) + ' ' + ' Anos'
print(descricao_idade)

